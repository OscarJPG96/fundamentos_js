//operadores de comparacion

let x = 5; // asignacion

//operador == comparar

console.log(x == 6);// false
console.log(x == 5);// true
 console.log(x == "5");//true

//operador === compara el valor y el tipo de dato
 console.log(x === 5);// true
  console.log(x === "5");// false


//!= comparar si dos objetos son diferentes
 console.log(x != 8); //true si son diferentes
console.log(x !== 5);//false no son diferentes

// !== diferente valor como el tipo de dato
console.log(x !== 5);//false
console.log(x !== "5");//true

// > operador mayor que
console.log(x > 10);//false
console.log(x > 2);//true

// < operador menor que

 console.log(x < 10);//true
 console.log(x < 2);// false

 //operador >= mayor o igual que
console.log(x >= 4);// true
console.log(x >= 5);//true
 console.log(x >= 6);//false
 

